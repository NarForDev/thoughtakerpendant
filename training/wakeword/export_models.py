"""Writes firmware/pendant/wake_models.h from the three trained models; the pendant builds with the wake word
only when that file exists. Cutoffs are the probability (0..1) a model must average over its sliding window."""
import argparse
import pathlib

parser = argparse.ArgumentParser()
parser.add_argument("--work", default="/root/mww/work")
parser.add_argument("--out", default="firmware/pendant/wake_models.h")
for p in ("perthro", "perthro_mark", "perthro_forget"):
    parser.add_argument(f"--{p}_cutoff", type=float, default=0.95)
args = parser.parse_args()

lines = ["// Generated by training/wakeword/export_models.py; do not edit", "#pragma once", ""]
for p in ("perthro", "perthro_mark", "perthro_forget"):
    data = pathlib.Path(args.work, p, "model/tflite_stream_state_internal_quant/stream_state_internal_quant.tflite").read_bytes()
    lines.append(f"// {len(data)} bytes; TFLite Micro needs the flatbuffer 16-byte aligned")
    lines.append(f"alignas(16) const unsigned char {p}_tflite[] = {{")
    lines += ["  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + "," for i in range(0, len(data), 16)]
    lines += ["};", f"const float {p}_cutoff = {getattr(args, p + '_cutoff')}f;", ""]
pathlib.Path(args.out).write_text("\n".join(lines))
print(f"wrote {args.out}")
